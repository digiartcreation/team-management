-- Calendar entries shared with selected people.
--
-- "Who can see it" on a calendar entry gains a third choice beside Only me and
-- Everyone: Selected people, picked from a list like a task's watchers. One
-- new table:
--
--   CalendarEventShare   one row per person a "selected" entry is shared with.
--                        They see the entry on their calendar and are notified
--                        when added; only its author changes it.
--
-- CalendarEvent.visibility gains the value "selected". It is a VARCHAR, so no
-- column changes.
--
-- Run AFTER prisma/add-calendar-events.sql (this table points at CalendarEvent).
-- Run in phpMyAdmin (hPanel -> Databases -> Enter phpMyAdmin -> SQL tab)
-- against BOTH databases, BEFORE deploying the code: the calendar reads this
-- table and fails until it exists.
--   u230921990_office          (production, used by the live site)
--   u230921990_office_testing  (whatever local .env points at)
--
-- DDL generated by Prisma, not hand-written:
--   npx prisma migrate diff --from-schema-datamodel <pre-change schema> \
--       --to-schema-datamodel prisma/schema.prisma --script
-- Only IF NOT EXISTS is hand-added.
--
-- Nothing is dropped and no existing row changes.


-- ---------------------------------------------------------------------------
-- STEP 1 - preflight.
-- ---------------------------------------------------------------------------
-- Expect ONE row. Empty means add-calendar-events.sql has not been run here
-- yet: run that first.
SHOW TABLES LIKE 'CalendarEvent';

-- Expect EMPTY. A row means step 2 is already applied here.
SHOW TABLES LIKE 'CalendarEventShare';


-- ---------------------------------------------------------------------------
-- STEP 2 - the migration.
-- ---------------------------------------------------------------------------
-- CREATE TABLE is guarded by IF NOT EXISTS and is safe to re-run. The foreign
-- keys are not: a second run fails with #1826 (duplicate foreign key; errno 121
-- on MariaDB), which is harmless and means this database already has them.

-- CreateTable
CREATE TABLE IF NOT EXISTS `CalendarEventShare` (
    `id` VARCHAR(191) NOT NULL,
    `eventId` VARCHAR(191) NOT NULL,
    `userId` VARCHAR(191) NOT NULL,
    `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),

    INDEX `CalendarEventShare_userId_fkey`(`userId`),
    UNIQUE INDEX `CalendarEventShare_eventId_userId_key`(`eventId`, `userId`),
    PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

-- AddForeignKey
-- Deleting the entry or the person removes the share, which means nothing
-- without both.
ALTER TABLE `CalendarEventShare` ADD CONSTRAINT `CalendarEventShare_eventId_fkey` FOREIGN KEY (`eventId`) REFERENCES `CalendarEvent`(`id`) ON DELETE CASCADE ON UPDATE CASCADE;

ALTER TABLE `CalendarEventShare` ADD CONSTRAINT `CalendarEventShare_userId_fkey` FOREIGN KEY (`userId`) REFERENCES `User`(`id`) ON DELETE CASCADE ON UPDATE CASCADE;


-- ---------------------------------------------------------------------------
-- STEP 3 - verify. Uses SHOW rather than information_schema, which
-- shared-hosting users cannot read (MySQL error #1044).
-- ---------------------------------------------------------------------------
-- Expect the table with CONSTRAINT lines referencing CalendarEvent and User.
SHOW CREATE TABLE `CalendarEventShare`;
