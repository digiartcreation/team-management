-- The client SOP written in an editor, and a file attached to a documentation
-- page.
--
--   Client.sopContent        the SOP as sanitised HTML from CKEditor. The SOP
--                            file stays in ClientSop and is now the client
--                            form's optional File Upload field.
--   DocumentationAttachment  one optional file per documentation page, of any
--                            type, kept in the database (LONGBLOB) so a
--                            redeploy cannot lose it
--
-- Everything else in this change (watchers open to every user, the Watching
-- board, Owner and Communication Person as dropdowns) needs nothing in the
-- database.
--
-- DDL generated by Prisma, not hand-written:
--   npx prisma migrate diff --from-schema-datamodel <pre-change schema> \
--       --to-schema-datamodel prisma/schema.prisma --script
-- Only the AFTER clause is hand-added, so sopContent sits beside notes in
-- phpMyAdmin. It has no effect on behaviour.
--
-- Run in phpMyAdmin (hPanel -> Databases -> Enter phpMyAdmin -> SQL tab)
-- against BOTH databases, BEFORE deploying the code: the Clients and
-- Documentation pages read this column and table and fail until they exist.
--   u230921990_office          (production, used by the live site)
--   u230921990_office_testing  (whatever local .env points at)
--
-- Nothing is dropped and no existing row is changed.


-- ---------------------------------------------------------------------------
-- STEP 1 - preflight. Run this first and read the output.
-- ---------------------------------------------------------------------------
-- Expect EMPTY for each. A row means that part of step 2 is already applied.
SHOW COLUMNS FROM `Client` LIKE 'sopContent';
SHOW TABLES LIKE 'DocumentationAttachment';

-- An attachment can be up to 10 MB and is sent to the database in one packet.
-- Expect a Value of 16777216 (16 MB) or more, as for the SOP file. If it is
-- lower, uploads near the limit fail with "packet too big": ask Hostinger
-- support to raise it, or lower MAX_ATTACHMENT_BYTES in lib/uploads.ts.
SHOW VARIABLES LIKE 'max_allowed_packet';


-- ---------------------------------------------------------------------------
-- STEP 2 - the migration.
-- ---------------------------------------------------------------------------
-- CREATE TABLE is guarded by IF NOT EXISTS and is safe to re-run. The rest is
-- not: a second run fails with #1060 (duplicate column name) on the ALTER, or
-- #1826 (duplicate foreign key; errno 121 on MariaDB) on a constraint. Either
-- error is harmless and means this database already has it.

-- AlterTable
ALTER TABLE `Client` ADD COLUMN `sopContent` LONGTEXT NULL AFTER `notes`;

-- CreateTable
CREATE TABLE IF NOT EXISTS `DocumentationAttachment` (
    `id` VARCHAR(191) NOT NULL,
    `documentationId` VARCHAR(191) NOT NULL,
    `fileName` VARCHAR(191) NOT NULL,
    `mimeType` VARCHAR(191) NOT NULL,
    `size` INTEGER NOT NULL,
    `data` LONGBLOB NOT NULL,
    `uploadedById` VARCHAR(191) NULL,
    `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `updatedAt` DATETIME(3) NOT NULL,

    UNIQUE INDEX `DocumentationAttachment_documentationId_key`(`documentationId`),
    INDEX `DocumentationAttachment_uploadedById_fkey`(`uploadedById`),
    PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

-- AddForeignKey
-- A deleted page takes its attachment with it. A deleted uploader does not:
-- the file stays on the page and only loses who uploaded it.
ALTER TABLE `DocumentationAttachment` ADD CONSTRAINT `DocumentationAttachment_documentationId_fkey` FOREIGN KEY (`documentationId`) REFERENCES `Documentation`(`id`) ON DELETE CASCADE ON UPDATE CASCADE;

ALTER TABLE `DocumentationAttachment` ADD CONSTRAINT `DocumentationAttachment_uploadedById_fkey` FOREIGN KEY (`uploadedById`) REFERENCES `User`(`id`) ON DELETE SET NULL ON UPDATE CASCADE;


-- ---------------------------------------------------------------------------
-- STEP 3 - verify. Uses SHOW rather than information_schema, which
-- shared-hosting users cannot read (MySQL error #1044).
-- ---------------------------------------------------------------------------
-- Expect longtext, NULL allowed, no default.
SHOW COLUMNS FROM `Client` LIKE 'sopContent';

-- Expect the table with both CONSTRAINT lines, referencing Documentation and
-- User.
SHOW CREATE TABLE `DocumentationAttachment`;
