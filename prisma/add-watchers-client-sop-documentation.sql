-- Task watchers, client owner / communication person / SOP, the Meeting & Call
-- service, and the Documentation menu.
--
--   TaskWatcher          one row per person watching a task. A watcher sees the
--                        task in the Watching section of their dashboard and
--                        can log time on it.
--   Client.owner         free text, like contactPerson
--   Client.communicationPerson
--                        free text
--   ClientSop            the client's SOP file, one per client, kept in the
--                        database (LONGBLOB) so a redeploy cannot lose it
--   Documentation        a page: heading plus sanitised HTML from CKEditor
--   DocumentationImage   images uploaded from the editor, also LONGBLOB
--
-- Meeting & Call is now an always-included service, like Client Management,
-- and step 3 gives every existing client its row. Training & Coaches is an
-- internal-only service and needs nothing in the database.
--
-- DDL generated by Prisma, not hand-written:
--   npx prisma migrate diff --from-schema-datamodel <pre-change schema> \
--       --to-schema-datamodel prisma/schema.prisma --script
-- Only the AFTER clauses are hand-added, so the new Client columns sit beside
-- contactPerson in phpMyAdmin. They have no effect on behaviour.
--
-- Run in phpMyAdmin (hPanel -> Databases -> Enter phpMyAdmin -> SQL tab)
-- against BOTH databases, BEFORE deploying the code: the Clients, Tasks and
-- dashboard pages read these tables and columns and fail until they exist.
--   u230921990_office          (production, used by the live site)
--   u230921990_office_testing  (whatever local .env points at)
--
-- Nothing is dropped and no existing row is rewritten. Step 3 only adds rows.


-- ---------------------------------------------------------------------------
-- STEP 1 - preflight. Run this first and read the output.
-- ---------------------------------------------------------------------------
-- Expect EMPTY for each. A row means that part of step 2 is already applied.
SHOW TABLES LIKE 'TaskWatcher';
SHOW TABLES LIKE 'ClientSop';
SHOW TABLES LIKE 'Documentation';
SHOW TABLES LIKE 'DocumentationImage';
SHOW COLUMNS FROM `Client` LIKE 'owner';
SHOW COLUMNS FROM `Client` LIKE 'communicationPerson';

-- An SOP can be up to 10 MB and an image up to 5 MB, and each is sent to the
-- database in one packet. Expect a Value of 16777216 (16 MB) or more. If it is
-- lower, uploads near the limit fail with "packet too big": ask Hostinger
-- support to raise it, or lower MAX_SOP_BYTES in lib/uploads.ts to fit.
SHOW VARIABLES LIKE 'max_allowed_packet';


-- ---------------------------------------------------------------------------
-- STEP 2 - the migration.
-- ---------------------------------------------------------------------------
-- CREATE TABLE is guarded by IF NOT EXISTS and is safe to re-run. The rest is
-- not: a second run fails with #1060 (duplicate column name) on the ALTER, or
-- #1826 (duplicate foreign key; errno 121 on MariaDB) on a constraint. Either
-- error is harmless and means this database already has it.

-- AlterTable
ALTER TABLE `Client` ADD COLUMN `owner` VARCHAR(191) NULL AFTER `contactPerson`,
    ADD COLUMN `communicationPerson` VARCHAR(191) NULL AFTER `owner`;

-- CreateTable
CREATE TABLE IF NOT EXISTS `ClientSop` (
    `id` VARCHAR(191) NOT NULL,
    `clientId` VARCHAR(191) NOT NULL,
    `fileName` VARCHAR(191) NOT NULL,
    `mimeType` VARCHAR(191) NOT NULL,
    `size` INTEGER NOT NULL,
    `data` LONGBLOB NOT NULL,
    `uploadedById` VARCHAR(191) NULL,
    `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `updatedAt` DATETIME(3) NOT NULL,

    UNIQUE INDEX `ClientSop_clientId_key`(`clientId`),
    INDEX `ClientSop_uploadedById_fkey`(`uploadedById`),
    PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

-- CreateTable
CREATE TABLE IF NOT EXISTS `TaskWatcher` (
    `id` VARCHAR(191) NOT NULL,
    `taskId` VARCHAR(191) NOT NULL,
    `userId` VARCHAR(191) NOT NULL,
    `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),

    INDEX `TaskWatcher_userId_fkey`(`userId`),
    UNIQUE INDEX `TaskWatcher_taskId_userId_key`(`taskId`, `userId`),
    PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

-- CreateTable
CREATE TABLE IF NOT EXISTS `Documentation` (
    `id` VARCHAR(191) NOT NULL,
    `title` VARCHAR(191) NOT NULL,
    `content` LONGTEXT NOT NULL,
    `createdById` VARCHAR(191) NULL,
    `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `updatedAt` DATETIME(3) NOT NULL,

    INDEX `Documentation_createdById_fkey`(`createdById`),
    PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

-- CreateTable
CREATE TABLE IF NOT EXISTS `DocumentationImage` (
    `id` VARCHAR(191) NOT NULL,
    `mimeType` VARCHAR(191) NOT NULL,
    `size` INTEGER NOT NULL,
    `data` LONGBLOB NOT NULL,
    `uploadedById` VARCHAR(191) NULL,
    `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),

    INDEX `DocumentationImage_uploadedById_fkey`(`uploadedById`),
    PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

-- AddForeignKey
-- A deleted client takes its SOP with it. A deleted uploader does not: the
-- SOP stays and only loses who uploaded it.
ALTER TABLE `ClientSop` ADD CONSTRAINT `ClientSop_clientId_fkey` FOREIGN KEY (`clientId`) REFERENCES `Client`(`id`) ON DELETE CASCADE ON UPDATE CASCADE;

ALTER TABLE `ClientSop` ADD CONSTRAINT `ClientSop_uploadedById_fkey` FOREIGN KEY (`uploadedById`) REFERENCES `User`(`id`) ON DELETE SET NULL ON UPDATE CASCADE;

-- AddForeignKey
-- Deleting a task or a user removes the watch, which means nothing without both.
ALTER TABLE `TaskWatcher` ADD CONSTRAINT `TaskWatcher_taskId_fkey` FOREIGN KEY (`taskId`) REFERENCES `Task`(`id`) ON DELETE CASCADE ON UPDATE CASCADE;

ALTER TABLE `TaskWatcher` ADD CONSTRAINT `TaskWatcher_userId_fkey` FOREIGN KEY (`userId`) REFERENCES `User`(`id`) ON DELETE CASCADE ON UPDATE CASCADE;

-- AddForeignKey
-- Documentation outlives its author: the page and its images stay, unowned.
ALTER TABLE `Documentation` ADD CONSTRAINT `Documentation_createdById_fkey` FOREIGN KEY (`createdById`) REFERENCES `User`(`id`) ON DELETE SET NULL ON UPDATE CASCADE;

ALTER TABLE `DocumentationImage` ADD CONSTRAINT `DocumentationImage_uploadedById_fkey` FOREIGN KEY (`uploadedById`) REFERENCES `User`(`id`) ON DELETE SET NULL ON UPDATE CASCADE;


-- ---------------------------------------------------------------------------
-- STEP 3 - give every existing client Meeting & Call.
-- ---------------------------------------------------------------------------
-- New and re-saved clients get the row from the app. This adds it to the
-- rest, as 'Included' with no payment, the same as Client Management. Safe to
-- re-run: a client that already has the row is skipped.
INSERT INTO `ClientService`
  (`id`, `clientId`, `service`, `focus`, `paymentType`, `percentage`,
   `packageAmount`, `perUnitAmount`, `billingCycle`, `createdAt`, `updatedAt`)
SELECT
  REPLACE(UUID(), '-', ''), c.`id`, 'Meeting & Call', NULL, 'Included', NULL,
  NULL, NULL, NULL, NOW(3), NOW(3)
FROM `Client` c
WHERE NOT EXISTS (
  SELECT 1 FROM `ClientService` cs
  WHERE cs.`clientId` = c.`id` AND cs.`service` = 'Meeting & Call'
);


-- ---------------------------------------------------------------------------
-- STEP 4 - verify. Uses SHOW rather than information_schema, which
-- shared-hosting users cannot read (MySQL error #1044).
-- ---------------------------------------------------------------------------
-- Expect each table with its CONSTRAINT lines, referencing Client, Task and User.
SHOW CREATE TABLE `TaskWatcher`;
SHOW CREATE TABLE `ClientSop`;
SHOW CREATE TABLE `Documentation`;
SHOW CREATE TABLE `DocumentationImage`;

-- Expect both columns as varchar(191), NULL allowed, no default.
SHOW COLUMNS FROM `Client` LIKE 'owner';
SHOW COLUMNS FROM `Client` LIKE 'communicationPerson';

-- Expect 0: every client now has Meeting & Call.
SELECT COUNT(*) AS clients_without_meeting_and_call
FROM `Client` c
WHERE NOT EXISTS (
  SELECT 1 FROM `ClientService` cs
  WHERE cs.`clientId` = c.`id` AND cs.`service` = 'Meeting & Call'
);
