-- Combined indexes for the list, board and report queries. Each one matches a
-- query that filters on one column and sorts or ranges on another, so MySQL
-- reads just the rows it needs instead of scanning and sorting:
--
--   Task          status+updatedAt, assignee/team+status+updatedAt (the task
--                 boards); assignee/team+createdAt (the Tasks list for an
--                 employee or a manager); clientId+completedAt (Services Count)
--   TaskTimeLog   taskId+date (Base Price Report history), userId+date
--                 (Reports filtered to one employee)
--   DailyUpdate   userId+date            (an employee's own updates)
--   Learning      createdAt, userId+createdAt   (the Learnings list)
--   ToolUsage     date, userId+date             (the AI Tools list)
--   ResearchDocument  createdAt, userId+createdAt (the Research list)
--   ActivityLog   userId+createdAt       (an employee's own activity)
--   Notification  userId+type+isRead+createdAt (the banner and unread count,
--                 on every page)
--   FeedbackSubmission  createdAt, userId+createdAt (the Feedback Center list)
--
-- Run in phpMyAdmin against EACH database, QA first, then live. Order does not
-- matter, and the app works the same with or without them -- only faster with.
--
-- FIRST click the database in phpMyAdmin's left panel, THEN open its SQL tab.
-- The statements name no database, so they run against the selected one.
-- Nothing here reads information_schema.
--
-- DDL generated by Prisma, not hand-written:
--   npx prisma migrate diff --from-schema-datamodel <schema before> \
--       --to-schema-datamodel prisma/schema.prisma --script
--
-- Nothing is dropped and no row changes. Each index builds in seconds at this
-- size while the site stays up. "#1061 Duplicate key name" on a line means that
-- index is already there: skip that line and run the rest.


