SHOW INDEX FROM `Task`;
SHOW INDEX FROM `TaskTimeLog`;


-- ---------------------------------------------------------------------------
-- STEP 2 - create the indexes.
-- ---------------------------------------------------------------------------
CREATE INDEX `Task_status_updatedAt_idx` ON `Task`(`status`, `updatedAt`);
CREATE INDEX `Task_assignedToId_status_updatedAt_idx` ON `Task`(`assignedToId`, `status`, `updatedAt`);
CREATE INDEX `Task_teamId_status_updatedAt_idx` ON `Task`(`teamId`, `status`, `updatedAt`);
CREATE INDEX `Task_assignedToId_createdAt_idx` ON `Task`(`assignedToId`, `createdAt`);
CREATE INDEX `Task_teamId_createdAt_idx` ON `Task`(`teamId`, `createdAt`);
CREATE INDEX `Task_clientId_completedAt_idx` ON `Task`(`clientId`, `completedAt`);
CREATE INDEX `TaskTimeLog_taskId_date_idx` ON `TaskTimeLog`(`taskId`, `date`);
CREATE INDEX `TaskTimeLog_userId_date_idx` ON `TaskTimeLog`(`userId`, `date`);
CREATE INDEX `DailyUpdate_userId_date_idx` ON `DailyUpdate`(`userId`, `date`);
CREATE INDEX `Learning_createdAt_idx` ON `Learning`(`createdAt`);
CREATE INDEX `Learning_userId_createdAt_idx` ON `Learning`(`userId`, `createdAt`);
CREATE INDEX `ToolUsage_date_idx` ON `ToolUsage`(`date`);
CREATE INDEX `ToolUsage_userId_date_idx` ON `ToolUsage`(`userId`, `date`);
CREATE INDEX `ResearchDocument_createdAt_idx` ON `ResearchDocument`(`createdAt`);
CREATE INDEX `ResearchDocument_userId_createdAt_idx` ON `ResearchDocument`(`userId`, `createdAt`);
CREATE INDEX `ActivityLog_userId_createdAt_idx` ON `ActivityLog`(`userId`, `createdAt`);
CREATE INDEX `Notification_userId_type_isRead_createdAt_idx` ON `Notification`(`userId`, `type`, `isRead`, `createdAt`);
CREATE INDEX `FeedbackSubmission_createdAt_idx` ON `FeedbackSubmission`(`createdAt`);
CREATE INDEX `FeedbackSubmission_userId_createdAt_idx` ON `FeedbackSubmission`(`userId`, `createdAt`);


