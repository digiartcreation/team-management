-- A reason when declining a shared calendar entry.
--
-- Declining a "Selected people" calendar entry now asks why, and the entry's
-- details show the reason to everyone invited. One new column:
--
--   CalendarEventShare.responseReason   why they declined; empty otherwise,
--                                       and cleared again if they accept.
--
-- Run AFTER prisma/add-calendar-share-responses.sql (this adds beside its
-- `response` column).
-- Run in phpMyAdmin (hPanel -> Databases -> Enter phpMyAdmin -> SQL tab)
-- against BOTH databases, BEFORE deploying the code: the calendar reads this
-- column and fails until it exists.
--   u230921990_office          (production, used by the live site)
--   u230921990_office_testing  (whatever local .env points at)
--
-- DDL generated by Prisma, not hand-written:
--   npx prisma migrate diff --from-schema-datamodel <pre-change schema> \
--       --to-schema-datamodel prisma/schema.prisma --script
-- Only the AFTER clause is hand-added. It has no effect on behaviour.
--
-- Nothing is dropped and no existing row changes.


-- ---------------------------------------------------------------------------
-- STEP 1 - preflight.
-- ---------------------------------------------------------------------------
-- Expect ONE row. Empty means add-calendar-share-responses.sql has not been
-- run here yet: run that first.
SHOW COLUMNS FROM `CalendarEventShare` LIKE 'response';

-- Expect EMPTY. A row means step 2 is already applied here.
SHOW COLUMNS FROM `CalendarEventShare` LIKE 'responseReason';


-- ---------------------------------------------------------------------------
-- STEP 2 - the migration.
-- ---------------------------------------------------------------------------
-- Not re-runnable: a second run fails with #1060 (duplicate column name),
-- which is harmless and means this database already has it.

-- AlterTable
ALTER TABLE `CalendarEventShare` ADD COLUMN `responseReason` TEXT NULL AFTER `response`;


-- ---------------------------------------------------------------------------
-- STEP 3 - verify.
-- ---------------------------------------------------------------------------
-- Expect `responseReason` as text, NULL allowed.
SHOW COLUMNS FROM `CalendarEventShare` LIKE 'responseReason';
