-- Accept or decline a shared calendar entry.
--
-- People a "Selected people" calendar entry is shared with can now accept or
-- decline it, and everyone invited sees who has. Two new columns on the
-- share:
--
--   CalendarEventShare.response      "pending", "accepted" or "declined"
--                                    (CALENDAR_RESPONSES in lib/calendar.ts).
--                                    Every existing share starts "pending".
--   CalendarEventShare.respondedAt   when they last answered; empty until then.
--
-- Run AFTER prisma/add-calendar-event-shares.sql (this adds to its table).
-- Run in phpMyAdmin (hPanel -> Databases -> Enter phpMyAdmin -> SQL tab)
-- against BOTH databases, BEFORE deploying the code: the calendar reads these
-- columns and fails until they exist.
--   u230921990_office          (production, used by the live site)
--   u230921990_office_testing  (whatever local .env points at)
--
-- DDL generated by Prisma, not hand-written:
--   npx prisma migrate diff --from-schema-datamodel <pre-change schema> \
--       --to-schema-datamodel prisma/schema.prisma --script
-- Only the AFTER clauses are hand-added, so the columns sit beside `userId` in
-- phpMyAdmin. They have no effect on behaviour.
--
-- Nothing is dropped and no existing row changes, beyond starting "pending".


-- ---------------------------------------------------------------------------
-- STEP 1 - preflight.
-- ---------------------------------------------------------------------------
-- Expect ONE row. Empty means add-calendar-event-shares.sql has not been run
-- here yet: run that first.
SHOW TABLES LIKE 'CalendarEventShare';

-- Expect EMPTY. A row means step 2 is already applied here.
SHOW COLUMNS FROM `CalendarEventShare` LIKE 'response';


-- ---------------------------------------------------------------------------
-- STEP 2 - the migration.
-- ---------------------------------------------------------------------------
-- Not re-runnable: a second run fails with #1060 (duplicate column name),
-- which is harmless and means this database already has them.

-- AlterTable
ALTER TABLE `CalendarEventShare` ADD COLUMN `response` VARCHAR(191) NOT NULL DEFAULT 'pending' AFTER `userId`,
    ADD COLUMN `respondedAt` DATETIME(3) NULL AFTER `response`;


-- ---------------------------------------------------------------------------
-- STEP 3 - verify.
-- ---------------------------------------------------------------------------
-- Expect `response` varchar(191) NOT NULL default 'pending', and
-- `respondedAt` datetime(3) NULL.
SHOW COLUMNS FROM `CalendarEventShare`;
