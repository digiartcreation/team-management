-- Which days a repeating calendar entry falls on, and when it stops.
--
-- The calendar's Repeat choice now asks which weekdays a weekly entry falls
-- on (Monday and Thursday, say), which date of the month a monthly one does,
-- and optionally the last day it repeats. Three new columns, all empty for
-- every existing entry, which keep repeating exactly as before:
--
--   CalendarEvent.repeatDays       weekly: the weekdays, Monday 1 to Sunday 7,
--                                  as "1,4". Empty means the start date's own
--                                  weekday.
--   CalendarEvent.repeatMonthDay   monthly: the day of the month, 1 to 31.
--                                  Empty means the start date's day.
--   CalendarEvent.repeatUntil      the last day it can fall on. Empty repeats
--                                  for good.
--
-- Run AFTER prisma/add-calendar-recurrence.sql (this adds to its column).
-- Run in phpMyAdmin (hPanel -> Databases -> Enter phpMyAdmin -> SQL tab)
-- against BOTH databases, BEFORE deploying the code: the calendar reads these
-- columns and fails until they exist.
--   u230921990_office          (production, used by the live site)
--   u230921990_office_testing  (whatever local .env points at)
--
-- DDL generated by Prisma, not hand-written:
--   npx prisma migrate diff --from-schema-datamodel <pre-change schema> \
--       --to-schema-datamodel prisma/schema.prisma --script
-- Only the AFTER clauses are hand-added, so the columns sit beside
-- `recurrence` in phpMyAdmin. They have no effect on behaviour.
--
-- Nothing is dropped and no existing row changes.


-- ---------------------------------------------------------------------------
-- STEP 1 - preflight.
-- ---------------------------------------------------------------------------
-- Expect ONE row. Empty means add-calendar-recurrence.sql has not been run
-- here yet: run that first.
SHOW COLUMNS FROM `CalendarEvent` LIKE 'recurrence';

-- Expect EMPTY. A row means step 2 is already applied here.
SHOW COLUMNS FROM `CalendarEvent` LIKE 'repeat%';


-- ---------------------------------------------------------------------------
-- STEP 2 - the migration.
-- ---------------------------------------------------------------------------
-- Not re-runnable: a second run fails with #1060 (duplicate column name),
-- which is harmless and means this database already has them.

-- AlterTable
ALTER TABLE `CalendarEvent` ADD COLUMN `repeatDays` VARCHAR(191) NULL AFTER `recurrence`,
    ADD COLUMN `repeatMonthDay` INTEGER NULL AFTER `repeatDays`,
    ADD COLUMN `repeatUntil` DATE NULL AFTER `repeatMonthDay`;


-- ---------------------------------------------------------------------------
-- STEP 3 - verify.
-- ---------------------------------------------------------------------------
-- Expect three rows: repeatDays varchar(191), repeatMonthDay int, repeatUntil
-- date, all NULL allowed with no default.
SHOW COLUMNS FROM `CalendarEvent` LIKE 'repeat%';
