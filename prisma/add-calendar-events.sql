-- The dashboard calendar.
--
-- Every dashboard (admin, manager, employee) now has a month calendar where
-- anyone can note a meeting, a client meeting, a training session or anything
-- else against a day, and edit or delete it later. One new table:
--
--   CalendarEvent   one entry: title, type, day, optional start and end time
--                   ("HH:MM"), optional notes, and who sees it -- "private"
--                   (its author only, the default) or "everyone". Its author
--                   can change it; admins can also change shared entries.
--
-- Run in phpMyAdmin (hPanel -> Databases -> Enter phpMyAdmin -> SQL tab)
-- against BOTH databases, BEFORE deploying the code: all three dashboards read
-- this table and fail until it exists.
--   u230921990_office          (production, used by the live site)
--   u230921990_office_testing  (whatever local .env points at)
--
-- DDL generated by Prisma, not hand-written:
--   npx prisma migrate diff --from-schema-datamodel <pre-change schema> \
--       --to-schema-datamodel prisma/schema.prisma --script
-- Only IF NOT EXISTS is hand-added.
--
-- Nothing is dropped and no existing row changes.


-- ---------------------------------------------------------------------------
-- STEP 1 - preflight.
-- ---------------------------------------------------------------------------
-- Expect EMPTY. A row means step 2 is already applied here.
SHOW TABLES LIKE 'CalendarEvent';


-- ---------------------------------------------------------------------------
-- STEP 2 - the migration.
-- ---------------------------------------------------------------------------
-- CREATE TABLE is guarded by IF NOT EXISTS and is safe to re-run. The foreign
-- key is not: a second run fails with #1826 (duplicate foreign key; errno 121
-- on MariaDB), which is harmless and means this database already has it.

-- CreateTable
CREATE TABLE IF NOT EXISTS `CalendarEvent` (
    `id` VARCHAR(191) NOT NULL,
    `title` VARCHAR(191) NOT NULL,
    `type` VARCHAR(191) NOT NULL,
    `date` DATE NOT NULL,
    `startTime` VARCHAR(191) NULL,
    `endTime` VARCHAR(191) NULL,
    `notes` TEXT NULL,
    `visibility` VARCHAR(191) NOT NULL DEFAULT 'private',
    `createdById` VARCHAR(191) NOT NULL,
    `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `updatedAt` DATETIME(3) NOT NULL,

    INDEX `CalendarEvent_date_idx`(`date`),
    INDEX `CalendarEvent_createdById_fkey`(`createdById`),
    PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

-- AddForeignKey
-- Deleting a user deletes their calendar entries, shared ones included.
ALTER TABLE `CalendarEvent` ADD CONSTRAINT `CalendarEvent_createdById_fkey` FOREIGN KEY (`createdById`) REFERENCES `User`(`id`) ON DELETE CASCADE ON UPDATE CASCADE;


-- ---------------------------------------------------------------------------
-- STEP 3 - verify. Uses SHOW rather than information_schema, which
-- shared-hosting users cannot read (MySQL error #1044).
-- ---------------------------------------------------------------------------
-- Expect the table with a CONSTRAINT line referencing User ON DELETE CASCADE.
SHOW CREATE TABLE `CalendarEvent`;
