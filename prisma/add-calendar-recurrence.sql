-- Repeating calendar entries.
--
-- A calendar entry can now repeat: set one date and it shows every week or
-- every month from then on (a weekly meeting, a monthly review). One new
-- column:
--
--   CalendarEvent.recurrence   "none", "weekly" or "monthly"
--                              (CALENDAR_RECURRENCES in lib/calendar.ts).
--                              Every existing entry becomes "none", so none
--                              of them changes.
--
-- The new Reminder type needs nothing in the database: the type is a VARCHAR.
--
-- Run AFTER prisma/add-calendar-events.sql (this adds to CalendarEvent).
-- Run in phpMyAdmin (hPanel -> Databases -> Enter phpMyAdmin -> SQL tab)
-- against BOTH databases, BEFORE deploying the code: the calendar reads this
-- column and fails until it exists.
--   u230921990_office          (production, used by the live site)
--   u230921990_office_testing  (whatever local .env points at)
--
-- DDL generated by Prisma, not hand-written:
--   npx prisma migrate diff --from-schema-datamodel <pre-change schema> \
--       --to-schema-datamodel prisma/schema.prisma --script
-- Only the AFTER clause is hand-added, so the column sits beside the times in
-- phpMyAdmin. It has no effect on behaviour.
--
-- Nothing is dropped and no existing row changes.


-- ---------------------------------------------------------------------------
-- STEP 1 - preflight.
-- ---------------------------------------------------------------------------
-- Expect EMPTY. A row means step 2 is already applied here.
SHOW COLUMNS FROM `CalendarEvent` LIKE 'recurrence';


-- ---------------------------------------------------------------------------
-- STEP 2 - the migration.
-- ---------------------------------------------------------------------------
-- Not re-runnable: a second run fails with #1060 (duplicate column name),
-- which is harmless and means this database already has it.

-- AlterTable
ALTER TABLE `CalendarEvent` ADD COLUMN `recurrence` VARCHAR(191) NOT NULL DEFAULT 'none' AFTER `endTime`;


-- ---------------------------------------------------------------------------
-- STEP 3 - verify.
-- ---------------------------------------------------------------------------
-- Expect `recurrence` as varchar(191), NOT NULL, default 'none'.
SHOW COLUMNS FROM `CalendarEvent` LIKE 'recurrence';
