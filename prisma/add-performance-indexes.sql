-- Indexes for the columns the app filters and sorts on, on tables that grow
-- every day. Without them MySQL reads the whole table each time, so pages got
-- slower month by month:
--
--   Task               status, updatedAt, completedAt, createdAt, clientWork
--                      (board columns and counts, the menu badge, Services
--                      Count, the Tasks list, the client work filter)
--   DailyUpdate        date, updatedAt   (the Updates list, the menu badge)
--   Learning           updatedAt         (the menu badge)
--   ToolUsage          updatedAt         (the menu badge)
--   ActivityLog        createdAt, entityType (the Activity list and filter)
--   Notification       userId + isRead + createdAt (unread count and banner,
--                      on every page)
--   AttendanceSession  checkOutTime      (open sessions, on every attendance
--                      view and check-in)
--
-- Run in phpMyAdmin against BOTH databases. Order does not matter: the code
-- works the same with or without these, it is only faster with them.
--   u230921990_office          (production, used by the live site)
--   u230921990_office_testing  (whatever local .env points at)
--
-- FIRST click the database in phpMyAdmin's left panel, THEN open its SQL tab
-- (hPanel -> Databases -> Enter phpMyAdmin -> <database> -> SQL). The
-- statements below name no database, so they run against the selected one;
-- with none selected, or information_schema selected, MySQL answers
-- "#1044 - Access denied ... to database 'information_schema'". Nothing here
-- reads information_schema, so phpMyAdmin has no reason to switch to it.
--
-- DDL generated by Prisma, not hand-written:
--   npx prisma migrate diff --from-schema-datamodel <pre-change schema> \
--       --to-schema-datamodel prisma/schema.prisma --script
--
-- Nothing is dropped and no row changes. Each index builds in a few seconds
-- at this size, while the site stays up.


-- ---------------------------------------------------------------------------
-- STEP 1 - preflight.
-- ---------------------------------------------------------------------------
-- Expect EMPTY. A row means that index already exists here: drop its line
-- from step 2 (running it again stops with "Duplicate key name", which is
-- harmless but stops the lines after it).
SHOW INDEX FROM `Task` WHERE Key_name IN ('Task_status_idx', 'Task_updatedAt_idx', 'Task_completedAt_idx', 'Task_createdAt_idx', 'Task_clientWork_idx');
SHOW INDEX FROM `DailyUpdate` WHERE Key_name IN ('DailyUpdate_date_idx', 'DailyUpdate_updatedAt_idx');
SHOW INDEX FROM `Learning` WHERE Key_name = 'Learning_updatedAt_idx';
SHOW INDEX FROM `ToolUsage` WHERE Key_name = 'ToolUsage_updatedAt_idx';
SHOW INDEX FROM `ActivityLog` WHERE Key_name IN ('ActivityLog_createdAt_idx', 'ActivityLog_entityType_idx');
SHOW INDEX FROM `Notification` WHERE Key_name = 'Notification_userId_isRead_createdAt_idx';
SHOW INDEX FROM `AttendanceSession` WHERE Key_name = 'AttendanceSession_checkOutTime_idx';


-- ---------------------------------------------------------------------------
-- STEP 2 - create the indexes.
-- ---------------------------------------------------------------------------
CREATE INDEX `Task_status_idx` ON `Task`(`status`);
CREATE INDEX `Task_updatedAt_idx` ON `Task`(`updatedAt`);
CREATE INDEX `Task_completedAt_idx` ON `Task`(`completedAt`);
CREATE INDEX `Task_createdAt_idx` ON `Task`(`createdAt`);
CREATE INDEX `Task_clientWork_idx` ON `Task`(`clientWork`);
CREATE INDEX `DailyUpdate_date_idx` ON `DailyUpdate`(`date`);
CREATE INDEX `DailyUpdate_updatedAt_idx` ON `DailyUpdate`(`updatedAt`);
CREATE INDEX `Learning_updatedAt_idx` ON `Learning`(`updatedAt`);
CREATE INDEX `ToolUsage_updatedAt_idx` ON `ToolUsage`(`updatedAt`);
CREATE INDEX `ActivityLog_createdAt_idx` ON `ActivityLog`(`createdAt`);
CREATE INDEX `ActivityLog_entityType_idx` ON `ActivityLog`(`entityType`);
CREATE INDEX `Notification_userId_isRead_createdAt_idx` ON `Notification`(`userId`, `isRead`, `createdAt`);
CREATE INDEX `AttendanceSession_checkOutTime_idx` ON `AttendanceSession`(`checkOutTime`);


-- ---------------------------------------------------------------------------
-- STEP 3 - check.
-- ---------------------------------------------------------------------------
-- Expect, in order: 5 rows, 2, 1, 1, 2, 1, 1 -- one per index above.
SHOW INDEX FROM `Task` WHERE Seq_in_index = 1 AND Key_name IN ('Task_status_idx', 'Task_updatedAt_idx', 'Task_completedAt_idx', 'Task_createdAt_idx', 'Task_clientWork_idx');
SHOW INDEX FROM `DailyUpdate` WHERE Seq_in_index = 1 AND Key_name IN ('DailyUpdate_date_idx', 'DailyUpdate_updatedAt_idx');
SHOW INDEX FROM `Learning` WHERE Seq_in_index = 1 AND Key_name = 'Learning_updatedAt_idx';
SHOW INDEX FROM `ToolUsage` WHERE Seq_in_index = 1 AND Key_name = 'ToolUsage_updatedAt_idx';
SHOW INDEX FROM `ActivityLog` WHERE Seq_in_index = 1 AND Key_name IN ('ActivityLog_createdAt_idx', 'ActivityLog_entityType_idx');
SHOW INDEX FROM `Notification` WHERE Seq_in_index = 1 AND Key_name = 'Notification_userId_isRead_createdAt_idx';
SHOW INDEX FROM `AttendanceSession` WHERE Seq_in_index = 1 AND Key_name = 'AttendanceSession_checkOutTime_idx';
