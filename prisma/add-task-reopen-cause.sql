-- Whose side sent a task back: "Because of client" or "Because of us".
--
-- Reopening a task from the dashboard board or the Tasks page now asks which,
-- defaulting to the client. One new column:
--
--   TaskReopen.cause   "client" or "team" (REOPEN_CAUSES in lib/taskStatus.ts).
--                      NULL for reopens from the task form, which does not
--                      ask, and for every reopen recorded before this.
--
-- Run against BOTH databases, BEFORE deploying the code: the Tasks and Reports
-- pages read this column and fail until it exists.
--   u230921990_office          (production, used by the live site)
--   u230921990_office_testing  (whatever local .env points at)
--
-- DDL generated by Prisma, not hand-written:
--   npx prisma migrate diff --from-schema-datamodel <pre-change schema> \
--       --to-schema-datamodel prisma/schema.prisma --script
-- Only the AFTER clause is hand-added, so the column sits beside `reason` in
-- phpMyAdmin. It has no effect on behaviour.
--
-- Nothing is dropped and no existing row changes: old reopens keep a NULL
-- cause and show without one.


-- ---------------------------------------------------------------------------
-- STEP 1 - preflight.
-- ---------------------------------------------------------------------------
-- Expect EMPTY. A row means step 2 is already applied here.
SHOW COLUMNS FROM `TaskReopen` LIKE 'cause';


-- ---------------------------------------------------------------------------
-- STEP 2 - the migration.
-- ---------------------------------------------------------------------------
-- Not re-runnable: a second run fails with #1060 (duplicate column name),
-- which is harmless and means this database already has it.

-- AlterTable
ALTER TABLE `TaskReopen` ADD COLUMN `cause` VARCHAR(191) NULL AFTER `reason`;


-- ---------------------------------------------------------------------------
-- STEP 3 - verify.
-- ---------------------------------------------------------------------------
-- Expect `cause` as varchar(191), NULL allowed, no default.
SHOW COLUMNS FROM `TaskReopen` LIKE 'cause';
