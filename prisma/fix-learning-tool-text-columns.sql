-- No length limit on Learnings and AI Tools text.
--
-- These columns were varchar(191), so a Learning's title, description or
-- reference link, or an AI Tools entry's tool name, purpose or outcome,
-- failed to save once it ran past 191 characters. They become TEXT, as the
-- Daily Update columns already are (prisma/fix-dailyupdate-text-columns.sql):
--
--   Learning.title, Learning.description, Learning.referenceLink
--   ToolUsage.toolName, ToolUsage.purpose, ToolUsage.outcome
--
-- Widening only: varchar(191) -> TEXT loses no data and no row is rewritten.
-- Safe to re-run: modifying a column to the type it already has is a no-op.
--
-- Run in phpMyAdmin (hPanel -> Databases -> Enter phpMyAdmin -> SQL tab)
-- against BOTH databases, BEFORE deploying the code.
--   u230921990_office          (production, used by the live site)
--   u230921990_office_testing  (whatever local .env points at)
--
-- DDL generated by Prisma, not hand-written:
--   npx prisma migrate diff --from-schema-datamodel <pre-change schema> \
--       --to-schema-datamodel prisma/schema.prisma --script


-- ---------------------------------------------------------------------------
-- STEP 1 - the migration.
-- ---------------------------------------------------------------------------

-- AlterTable
ALTER TABLE `Learning` MODIFY `title` TEXT NOT NULL,
    MODIFY `description` TEXT NOT NULL,
    MODIFY `referenceLink` TEXT NULL;

-- AlterTable
ALTER TABLE `ToolUsage` MODIFY `toolName` TEXT NOT NULL,
    MODIFY `purpose` TEXT NOT NULL,
    MODIFY `outcome` TEXT NULL;


-- ---------------------------------------------------------------------------
-- STEP 2 - verify. Uses SHOW rather than information_schema, which
-- shared-hosting users cannot read (MySQL error #1044).
-- ---------------------------------------------------------------------------
-- Expect title, description and referenceLink to read `text`.
SHOW COLUMNS FROM `Learning`;

-- Expect toolName, purpose and outcome to read `text`.
SHOW COLUMNS FROM `ToolUsage`;
