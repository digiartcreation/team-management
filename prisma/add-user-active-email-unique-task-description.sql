-- Employee status, one account per email, and long task descriptions.
--
--   User.isActive       new. An inactive employee cannot sign in and is left
--                       out of the lists new work is assigned from. Every
--                       existing employee starts active.
--   Task.description    VARCHAR(191) -> TEXT. The task form now has a
--                       formatting editor and no length limit; anything past
--                       191 characters failed to save.
--   User.email          a unique index: one account per email address.
--
-- Run in phpMyAdmin (hPanel -> Databases -> Enter phpMyAdmin -> SQL tab)
-- against BOTH databases, BEFORE deploying the code: the app reads isActive
-- on every sign-in and fails until it exists.
--   u230921990_office          (production, used by the live site)
--   u230921990_office_testing  (whatever local .env points at)
--
-- DDL generated by Prisma, not hand-written:
--   npx prisma migrate diff --from-schema-datamodel <pre-change schema> \
--       --to-schema-datamodel prisma/schema.prisma --script
-- Only the AFTER clause is hand-added. It has no effect on behaviour.
--
-- Nothing is dropped and no existing row changes.


-- ---------------------------------------------------------------------------
-- STEP 1 - preflight.
-- ---------------------------------------------------------------------------
-- Expect EMPTY. A row means step 2 is already applied here.
SHOW COLUMNS FROM `User` LIKE 'isActive';

-- Expect `description` as varchar(191). text means step 2 is already applied.
SHOW COLUMNS FROM `Task` LIKE 'description';

-- Expect EMPTY. Each row is an email more than one account uses; step 4
-- cannot run until every one of them is down to a single account, which
-- step 3 does.
SELECT LOWER(`email`) AS `email`, COUNT(*) AS `accounts`
FROM `User`
GROUP BY LOWER(`email`)
HAVING COUNT(*) > 1;


-- ---------------------------------------------------------------------------
-- STEP 2 - the migration. Run this even if step 1 listed shared emails.
-- ---------------------------------------------------------------------------
-- Not re-runnable as a whole: a second run fails on the first statement with
-- #1060 (duplicate column name), which is harmless and means it is applied.

-- AlterTable
ALTER TABLE `User` ADD COLUMN `isActive` BOOLEAN NOT NULL DEFAULT true AFTER `designation`;

-- AlterTable
ALTER TABLE `Task` MODIFY `description` TEXT NULL;


-- ---------------------------------------------------------------------------
-- STEP 3 - shared emails. Only if step 1's last query listed any.
-- ---------------------------------------------------------------------------
-- Before, one person could have an account per role on the same email. Each
-- address now belongs to one account, so the extra ones need their own.
--
-- 3a. Who shares an email, oldest account first, with how much work each has.
SELECT u.`id`, u.`name`, u.`email`, u.`role`, u.`createdAt`,
       (SELECT COUNT(*) FROM `Task` t WHERE t.`assignedToId` = u.`id`) AS `tasks`,
       (SELECT COUNT(*) FROM `TaskTimeLog` l WHERE l.`userId` = u.`id`) AS `timeEntries`
FROM `User` u
WHERE LOWER(u.`email`) IN (
  SELECT LOWER(`email`) FROM `User` GROUP BY LOWER(`email`) HAVING COUNT(*) > 1
)
ORDER BY LOWER(u.`email`), u.`createdAt`;

-- 3b. The oldest account on each shared email keeps it. Every later one gets
-- "+its role" before the @, e.g. name+admin@gmail.com: Gmail and most mail
-- services deliver that to the same inbox, and it is what that account signs
-- in with from now on. Unique, as an email already had one account per role.
-- Nothing the accounts did changes. (To pick which account keeps the plain
-- address instead, change the others' emails on Employees -> Edit and skip
-- this.)
UPDATE `User` u
JOIN (
  SELECT `id` FROM (
    SELECT `id`,
           ROW_NUMBER() OVER (PARTITION BY LOWER(`email`) ORDER BY `createdAt`, `id`) AS `n`
    FROM `User`
  ) ranked
  WHERE `n` > 1
) extra ON extra.`id` = u.`id`
SET u.`email` = LOWER(CONCAT(
  SUBSTRING_INDEX(u.`email`, '@', 1), '+', u.`role`, '@', SUBSTRING_INDEX(u.`email`, '@', -1)
));


-- ---------------------------------------------------------------------------
-- STEP 4 - one account per email. Once step 1's last query comes back empty.
-- ---------------------------------------------------------------------------
-- With shared emails left it fails with #1062 (duplicate entry) and changes
-- nothing; do step 3 and run it again. The app already refuses a new account
-- or an edit that would reuse an email, so this can wait until then.
-- A second run fails with #1061 (duplicate key name): already applied.

-- CreateIndex
CREATE UNIQUE INDEX `User_email_key` ON `User`(`email`);


-- ---------------------------------------------------------------------------
-- STEP 5 - verify.
-- ---------------------------------------------------------------------------
-- Expect `isActive` as tinyint(1), default 1.
SHOW COLUMNS FROM `User` LIKE 'isActive';

-- Expect `description` as text.
SHOW COLUMNS FROM `Task` LIKE 'description';

-- Expect one row, Non_unique 0.
SHOW INDEX FROM `User` WHERE Key_name = 'User_email_key';
